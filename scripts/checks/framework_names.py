"""The framework names a question must never show (spec 004 FR-001, SC-001).

Builds one case-insensitive regular expression from the shipped cards in
packs/frameworks/: each card's name, the text inside its parentheses as a
second name, and its id with dashes read as spaces or dashes. The eval grader
`no-framework-name.md` in every case under evals/frameworks/ uses this pattern
with `tool_used`, `tool: AskUserQuestion`, `min: 0`, `max: 0`, so a question,
option, description or preview that names a framework fails the case.

EXEMPT cards are left out: an organization's own OKRs come from its ground
rules, so a question may name them (spec 004 Edge Cases).

Python 3.10+ standard library only.

Run: python3 scripts/checks/framework_names.py            # print the pattern
     python3 scripts/checks/framework_names.py --write    # rewrite every grader
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from frontmatter import load  # noqa: E402

REPO = HERE.parent.parent
CARDS_DIR = REPO / "packs" / "frameworks"
CASES_DIR = REPO / "evals" / "frameworks"
GRADER_NAME = "no-framework-name.md"
TEXT_GRADER_NAME = "no-framework-name-in-text.md"
EXEMPT = {"okr"}


def _caseless(text: str) -> str:
    """A regex for text, matching letters in either case and any run of spaces or dashes."""
    out = []
    for word in re.split(r"[\s-]+", text.strip()):
        part = []
        for ch in word:
            if ch.isalpha() and ch.lower() != ch.upper():
                part.append(f"[{ch.upper()}{ch.lower()}]")
            else:
                part.append(re.escape(ch))
        out.append("".join(part))
    return r"[\s-]+".join(out)


def names(cards_dir: Path = CARDS_DIR) -> list[str]:
    """Every name a question must not show, longest first, without duplicates."""
    found: set[str] = set()
    for card in sorted(cards_dir.glob("*.md")):
        data, _ = load(card)
        card_id = str(data.get("id") or card.stem)
        if card_id in EXEMPT:
            continue
        name = str(data.get("name") or "")
        inner = re.findall(r"\(([^)]*)\)", name)
        outer = re.sub(r"\s*\([^)]*\)", "", name).strip()
        for item in [outer, *inner, card_id.replace("-", " ")]:
            item = item.strip()
            if len(item) >= 3:
                found.add(item)
    return sorted(found, key=lambda s: (-len(s), s.lower()))


def pattern(cards_dir: Path = CARDS_DIR) -> str:
    return "|".join(_caseless(n) for n in names(cards_dir))


def grader_text(pat: str) -> str:
    quoted = pat.replace("'", "''")
    return (
        "---\n"
        "type: tool_used\n"
        "tool: 'AskUserQuestion'\n"
        f"input_match: '{quoted}'\n"
        "min: 0\n"
        "max: 0\n"
        "---\n\n"
        "No question, option, description or preview names a framework or asks the user to pick one "
        "(spec 004 FR-001). Generated by scripts/checks/framework_names.py --write; do not edit by hand.\n"
    )


def text_grader_text(pat: str) -> str:
    """The same names in the final message, where a headless run shows its questions as text."""
    quoted = pat.replace("'", "''")
    return (
        "---\n"
        "type: regex\n"
        "target: 'last_message'\n"
        "match: 'not_contains'\n"
        f"pattern: '{quoted}'\n"
        "---\n\n"
        "A run without the question tool shows its round as text; that text names no framework either "
        "(spec 004 FR-001). Generated by scripts/checks/framework_names.py --write; do not edit by hand.\n"
    )


def case_dirs(cases_dir: Path = CASES_DIR) -> list[Path]:
    return sorted(p for p in cases_dir.iterdir() if p.is_dir() and (p / "prompt.md").is_file())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="rewrite the grader in every framework case")
    args = parser.parse_args(argv)
    pat = pattern()
    if not args.write:
        print(pat)
        return 0
    text = grader_text(pat)
    for case in case_dirs():
        (case / "graders").mkdir(exist_ok=True)
        (case / "graders" / GRADER_NAME).write_text(text, encoding="utf-8")
        (case / "graders" / TEXT_GRADER_NAME).write_text(text_grader_text(pat), encoding="utf-8")
        print(f"wrote {case.name}/graders/{GRADER_NAME} and {TEXT_GRADER_NAME}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
